"""
dataset_loader.py
PyTorch Dataset and DataLoader for SIH Defence ANC audio pairs.
Reads directly from dataset manifest.json generated by mix_dataset.py.

BUG #1 FIX: Now loads primary_mic AND ref_mic, runs Python APSA→FLANN
simulation so the GRU trains on the DSP residual — exactly what the
ESP32 firmware will feed into the neural network stage.

BUG #19 FIX: Val/test splits use deterministic center-crop instead of
random crop, so evaluation is reproducible.
"""

import os
import json
import torch
import soundfile as sf
import numpy as np
from torch.utils.data import Dataset, DataLoader
from dsp_simulator import simulate_dsp_pipeline

class DefenceAudioDataset(Dataset):
    def __init__(self, manifest_path: str, split: str = 'train', 
                 target_duration_sec: float = 3.0, sample_rate: int = 16000,
                 return_raw: bool = False):
        super(DefenceAudioDataset, self).__init__()
        self.sample_rate = sample_rate
        self.target_len = int(target_duration_sec * sample_rate)
        self.split = split
        self.return_raw = return_raw
        self.samples = []
        self._cache = {}
        
        if not os.path.exists(manifest_path):
            raise FileNotFoundError(f"Manifest not found: {manifest_path}")
            
        with open(manifest_path, 'r') as f:
            all_entries = json.load(f)
            
        for entry in all_entries:
            if entry.get('split') == split:
                self.samples.append(entry)
                
        print(f"Loaded {len(self.samples)} samples for split: '{split}' from {manifest_path}")

    def __len__(self):
        return len(self.samples)

    def __getitem__(self, idx):
        if idx in self._cache:
            clean, dsp_residual, primary = self._cache[idx]
        else:
            entry = self.samples[idx]
            clean_path = entry['paths']['clean']
            primary_path = entry['paths']['primary_mic']
            ref_path = entry['paths']['ref_mic']
            
            clean, _ = sf.read(clean_path, dtype='float32')
            primary, _ = sf.read(primary_path, dtype='float32')
            ref_mic, _ = sf.read(ref_path, dtype='float32')
            
            # Run APSA → FLANN simulation to get the DSP residual
            dsp_residual = simulate_dsp_pipeline(primary, ref_mic)
            self._cache[idx] = (clean, dsp_residual, primary)
        
        # Ensure fixed length
        cur_len = min(len(clean), len(dsp_residual), len(primary))
        if cur_len < self.target_len:
            clean = np.pad(clean[:cur_len], (0, self.target_len - cur_len))
            dsp_residual = np.pad(dsp_residual[:cur_len], (0, self.target_len - cur_len))
            primary = np.pad(primary[:cur_len], (0, self.target_len - cur_len))
        else:
            if self.split == 'train':
                # Random crop for training augmentation
                start = np.random.randint(0, cur_len - self.target_len + 1)
            else:
                # BUG #19 FIX: Deterministic center-crop for val/test reproducibility
                start = (cur_len - self.target_len) // 2
            clean = clean[start : start + self.target_len]
            dsp_residual = dsp_residual[start : start + self.target_len]
            primary = primary[start : start + self.target_len]
            
        if self.return_raw:
            return torch.from_numpy(dsp_residual), torch.from_numpy(clean), torch.from_numpy(primary)
        return torch.from_numpy(dsp_residual), torch.from_numpy(clean)


def get_dataloaders(manifest_path: str, batch_size: int = 8, 
                    target_duration_sec: float = 3.0) -> tuple:
    train_set = DefenceAudioDataset(manifest_path, split='train', target_duration_sec=target_duration_sec)
    val_set = DefenceAudioDataset(manifest_path, split='val', target_duration_sec=target_duration_sec)
    test_set = DefenceAudioDataset(manifest_path, split='test', target_duration_sec=target_duration_sec)
    
    train_loader = DataLoader(train_set, batch_size=batch_size, shuffle=True, drop_last=False)
    val_loader = DataLoader(val_set, batch_size=batch_size, shuffle=False)
    test_loader = DataLoader(test_set, batch_size=1, shuffle=False)
    
    return train_loader, val_loader, test_loader
